% Upper One-sided VSI EWMA X-bar Chart for Gamma %
% Steady State %
% Search for lambda, hL, K1 and K2 %

function [lam, hL, K1, K2, EAATS1, AATS0, ASI0] = OptAtsUpperVsiEwmaXbarGamEAATS(n, hS, deltamin, deltamax, tau0, a_shape, b_scale)

% Initial guess
x0 = [0.1, 1.5, 0.65, 2.5];

% Bounds
lb = [0.05, 1.02, 0.6, 2.0];
ub = [1.00, 1.50, 1.5, 4.0];

options = optimoptions('fmincon', ...
    'Algorithm', 'interior-point', ...
    'TolFun', 1e-10, ...
    'TolX', 1e-10, ...
    'TolCon', 1e-10, ...
    'MaxIterations', 1000, ...
    'Display', 'off', ...
    'OutputFcn', @(x,optimValues,state) ...
        OutFunUpperVsiEwmaXbarGamEAATS( ...
        x, optimValues, state, ...
        n, hS, deltamin, deltamax, tau0, a_shape, b_scale));

x = fmincon(@(x) ...
    ObjUpperVsiEwmaXbarGamEAATS(x, n, hS, deltamin, deltamax, a_shape, b_scale), ...
    x0, [], [], [], [], lb, ub, ...
    @(x) ConUpperVsiEwmaXbarGamSteady(x, n, hS, tau0, a_shape, b_scale), ...
    options);

lam = x(1);
hL  = x(2);
K1  = x(3);
K2  = x(4);

% Final performance
EAATS1 = EAATSFindUpperVsiEwmaXbarGam(n, deltamin, deltamax, hL, hS, lam, K1, K2, a_shape, b_scale) ; 

[AATS0, ~, ASI0] = TsUpperVsiEwmaXbarGamSteady(n, hL, hS, lam, K1, K2, 0, a_shape, b_scale);

fprintf(['lam = %6.4f  hL = %6.4f  K1 = %6.4f  K2 = %6.4f  ', ...
         'AATS0 = %6.2f  ASI0 = %6.2f EAATS1 = %6.2f \n'], ...
         lam, hL, K1, K2, AATS0, ASI0, EAATS1);
end
